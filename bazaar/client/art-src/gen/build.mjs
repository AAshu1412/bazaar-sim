// node art-src/gen/build.mjs [name ...]   -> project/exterior/<name>.svg  and  public/assets/exterior/<name>.png
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import { Scene } from "./engine.mjs";
import { BUILDINGS as TOWN_BUILDINGS } from "./buildings.mjs";
import { SHOPS } from "./shops.mjs";
const BUILDINGS = { ...TOWN_BUILDINGS, ...SHOPS };

const here = fileURLToPath(new URL(".", import.meta.url));
const svgDir = `${here}../project/exterior/`, pngDir = `${here}../../public/assets/exterior/`;
fs.mkdirSync(svgDir, { recursive: true });
const names = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const png = process.argv.includes("--png");
if (png) fs.mkdirSync(pngDir, { recursive: true });
const kinds = {}, roofs = {};
for (const name of names.length ? names : Object.keys(BUILDINGS)) {
  const S = new Scene(name);
  BUILDINGS[name](S);
  kinds[name] = S.groundKind ?? "stone";
  const svg = S.svg();
  fs.writeFileSync(`${svgDir}${name}.svg`, svg);
  const image = new Resvg(svg, { fitTo: { mode: "width", value: 302 } }).render();
  if (png) fs.writeFileSync(`${pngDir}${name}.png`, image.asPng());
  if (name in SHOPS) { const px = image.pixels; for (let i = 3; i < px.length; i += 4) if (px[i] > 230) { roofs[name] = Math.floor(i / 4 / image.width); break; } }
  console.log("built", name);
}

if (!names.length) {
  fs.writeFileSync(`${here}../../src/engine/roofTops.ts`, `// generated by art-src/gen/build.mjs: first solid pixel row of each shop sprite (302x256)\nexport const ROOF_TOPS: Record<string, number> = ${JSON.stringify(roofs, null, 2)};\n`);
  fs.writeFileSync(`${here}../../src/engine/groundKinds.ts`, `// generated by art-src/gen/build.mjs: ground tile each building sits on\nexport const GROUND_KINDS: Record<string, "stone" | "cobble" | "grass" | "dirt"> = ${JSON.stringify(kinds, null, 2)};\n`);
}
