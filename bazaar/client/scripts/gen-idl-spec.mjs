// node scripts/gen-idl-spec.mjs  (after `yarn build` in the repo root) -> src/solana/idlSpec.ts
import fs from "node:fs";
const idl = JSON.parse(fs.readFileSync(new URL("../../target/idl/bazaar.json", import.meta.url), "utf8"));
const out = {};
for (const i of idl.instructions) {
  out[i.name] = { disc: i.discriminator, accounts: i.accounts.map((a) => [a.name, !!a.writable, !!a.signer]) };
}
fs.writeFileSync(new URL("../src/solana/idlSpec.ts", import.meta.url),
  `// generated by scripts/gen-idl-spec.mjs from target/idl/bazaar.json\nexport const IX: Record<string, { disc: number[]; accounts: [string, boolean, boolean][] }> = ${JSON.stringify(out, null, 1)};\n`);
console.log("instructions:", Object.keys(out).length);
